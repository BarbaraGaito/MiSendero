def base_features(base, frame):
    with torch.no_grad():
        standardized = base.transform(frame)
        logits = base.model(standardized)
    return standardized.float(), logits.detach()


def prepare_base(frame, specification):
    if frame["group_key"].nunique() < 3:
        raise ValueError("At least three fitting people are required for inner cross-fitting")
    control = {"steps": 0}
    logits = torch.empty((len(frame), 21), dtype=torch.float64)
    evidence = []
    for fit, val in GroupKFold(n_splits=3).split(frame, groups=frame["group_key"]):
        if set(frame.iloc[fit]["group_key"]) & set(frame.iloc[val]["group_key"]):
            raise ValueError("Joint-transfer baseline leaked inner participants")
        model = WarmPersonalBorg(control).fit(frame.iloc[fit], specification)
        logits[val] = base_features(model, frame.iloc[val])[1]
        evidence.append({"fit_row_keys": frame.iloc[fit]["row_key"].tolist(), "validation_row_keys": frame.iloc[val]["row_key"].tolist()})
    base = WarmPersonalBorg(control).fit(frame, specification)
    return {"base": base, "fit_logits": logits, "inner_folds": evidence, "fit_row_keys": frame["row_key"].tolist()}


class JointResidualNetwork(nn.Module):
    def __init__(self, n_sensor, n_context, domains):
        super().__init__()
        self.encoder = nn.Sequential(nn.Linear(n_sensor, 16), nn.Tanh(), nn.Linear(16, 8), nn.Tanh())
        self.corrector = nn.Sequential(nn.Linear(n_context+21+8, 16), nn.Tanh(), nn.Linear(16, 21))
        self.source_heads = nn.ModuleDict({name: nn.Linear(8, 1) for name in domains})
        nn.init.zeros_(self.corrector[-1].weight)
        nn.init.zeros_(self.corrector[-1].bias)

    def correction(self, sensor, context, base_logits):
        encoded = self.encoder(sensor)
        joined = torch.cat((context, torch.softmax(base_logits, dim=1).float(), encoded), dim=1)
        return self.corrector(joined).to(base_logits.dtype)

    def source_prediction(self, sensor, domain):
        return 10.*torch.sigmoid(self.source_heads[domain](self.encoder(sensor)).squeeze(1))


class JointBorg:
    def __init__(self, candidate):
        self.candidate = candidate

    def sensor_transform(self, frame):
        columns = self.candidate["sensor_features"]
        return torch.tensor(self.sensor_scaler.transform(self.sensor_imputer.transform(frame[columns])), dtype=torch.float32)

    def fit(self, frame, external, specification, cached=None):
        torch.set_num_threads(1)
        torch.use_deterministic_algorithms(True)
        cached = prepare_base(frame, specification) if cached is None else cached
        if cached["fit_row_keys"] != frame["row_key"].tolist():
            raise ValueError("Cached joint-transfer baseline belongs to other fitting rows")
        self.base = cached["base"]
        self.inner_folds = cached["inner_folds"]
        if self.candidate["algorithm"] == "incumbent_control":
            self.network = None
            return self
        if set(frame["group_key"]) & set(external["group_key"]):
            raise ValueError("Source participant namespaces collide with the original study")
        torch.manual_seed(42)
        np.random.seed(42)
        columns = self.candidate["sensor_features"]
        # The same fitting-only normalization is used for all auxiliary-loss
        # weights. External reserved people and original validation rows never
        # fit these statistics; missing sensors remain explicit indicators.
        union = pd.concat([frame[columns], external[columns]], ignore_index=True)
        self.sensor_imputer = SimpleImputer(strategy="median", keep_empty_features=True, add_indicator=True)
        self.sensor_scaler = StandardScaler().fit(self.sensor_imputer.fit_transform(union))
        sensor, context = self.sensor_transform(frame), base_features(self.base, frame)[0]
        offsets = cached["fit_logits"]
        target = torch.tensor(frame["label"].str.removeprefix("Borg ").to_numpy(int)-frame["prior_borg"].to_numpy(int)+10, dtype=torch.int64)
        self.domains = sorted(external["source_domain"].unique())
        self.source_report_counts = {name: int(external["source_domain"].eq(name).sum()) for name in self.domains}
        auxiliary = {}
        for name in self.domains:
            rows = external[external["source_domain"].eq(name)]
            values = rows["borg_native"].to_numpy(float)
            if not np.isfinite(values).all() or np.any((values < 0) | (values > 10)):
                raise ValueError("Auxiliary targets must remain original continuous CR10 values")
            auxiliary[name] = self.sensor_transform(rows), torch.tensor(values, dtype=torch.float32)
        self.network = JointResidualNetwork(sensor.shape[1], context.shape[1], self.domains)
        optimizer = torch.optim.AdamW(self.network.parameters(), lr=.003, weight_decay=.1)
        scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=self.candidate["epochs"], eta_min=.0003)
        for _ in range(self.candidate["epochs"]):
            optimizer.zero_grad(set_to_none=True)
            correction = self.network.correction(sensor, context, offsets)
            classification = nn.functional.cross_entropy(offsets+correction, target)
            losses = {name: nn.functional.smooth_l1_loss(self.network.source_prediction(x, name), y, beta=1.) for name, (x, y) in auxiliary.items()}
            auxiliary_loss = torch.stack(list(losses.values())).mean()
            penalty = .1*(correction**2).mean()
            total = classification+self.candidate["auxiliary_weight"]*auxiliary_loss+penalty
            if not torch.isfinite(total):
                raise ValueError("Nonfinite combined-source training loss")
            total.backward()
            if any(p.grad is not None and not torch.isfinite(p.grad).all() for p in self.network.parameters()):
                raise ValueError("Nonfinite shared sensor gradient")
            nn.utils.clip_grad_norm_(self.network.parameters(), 5.)
            optimizer.step()
            scheduler.step()
        self.training_losses = {"classification": float(classification.detach()), "auxiliary_mean": float(auxiliary_loss.detach()),
                                "source_losses": {name: float(value.detach()) for name, value in losses.items()}, "correction_penalty": float(penalty.detach())}
        return self

    def predict(self, frame):
        validate_calibration(frame)
        if self.network is None:
            return self.base.global_predict(frame)
        with torch.no_grad():
            context, offsets = base_features(self.base, frame)
            output = offsets+self.network.correction(self.sensor_transform(frame), context, offsets)
            if not torch.isfinite(output).all():
                raise ValueError("Nonfinite joint-transfer prediction")
            order = torch.tensor(self.base.model.priority)
            delta = order[output[:, order].argmax(dim=1)].numpy()-10
        return native_prediction(delta, frame["prior_borg"].to_numpy(int))


def plan():
    candidates = [{"id": "joint-source-000", "algorithm": "incumbent_control", "feature_set": "original_prior_control"}]
    for name, columns in (("shared_hr", ["hr_last", "hr_history_mean"]), ("shared_hr_and_gait", SENSOR_FEATURES)):
        for weight in (0., .1, 1.):
            for epochs in (80, 200):
                candidates.append({"id": f"joint-source-{len(candidates):03d}", "algorithm": "shared_sensor_residual_network",
                                   "feature_set": name, "sensor_features": columns, "auxiliary_weight": weight, "epochs": epochs,
                                   "encoder_widths": [16, 8], "residual_width": 16, "learning_rate": .003, "weight_decay": .1,
                                   "correction_penalty": .1, "source_loss": "separate_native_CR10_Huber_heads", "source_loss_weighting": "mean_per_domain", "random_seed": 42})
    return candidates


def load_inputs():
    frame, train, test, manifest, protocol = spectral_inputs()
    external, evidence = source_inputs()
    return frame, train, test, manifest, protocol, external, evidence


def fingerprint(manifest, source_manifest):
    helpers = ("fatigue_joint_sources.py", "fatigue_spectral_experiment.py", "fatigue_warm_sgd.py")
    return {"code_sha256": digest(Path(__file__)), "dataset_sha256": manifest["dataset_sha256"],
            "spectral_dataset_sha256": manifest["spectral_dataset_sha256"], "spectral_provenance_sha256": manifest["spectral_provenance_sha256"],
            "source_dataset_sha256": source_manifest["dataset_sha256"], "source_provenance_sha256": digest(SOURCE_DIRECTORY / "provenance.json"),
            "core_candidate": core_candidate(manifest), "external_splits": source_manifest["external_splits"],
            "dependency_code_sha256": {name: digest(Path(__file__).with_name(name)) for name in helpers},
            "software_versions": {name: importlib.metadata.version(name) for name in ("torch", "numpy", "pandas", "scikit-learn")}}


def select():
    _, train, _, manifest, _, external, source_manifest = load_inputs()
    candidates = plan()
    signature = {**fingerprint(manifest, source_manifest), "plan": candidates, "train_row_keys": train["row_key"].tolist()}
    DIRECTORY.mkdir(exist_ok=True)
    path = DIRECTORY / "selection.json"
    report = {**signature, "version": 1, "target_accuracy": .8, "status": "running", "results": [], "test_used_for_selection": False,
              "previous_benchmark_results_are_published": True, "external_test_used": False, "synthetic_rows": 0,
              "external_fitting_reports": 520, "external_domains": source_manifest["domains"], "native_momentary_target_merge": False,
              "evaluation_denominator": 487, "test_denominator": 179,
              "policy": "Four source-specific continuous CR10 regression heads share a sensor encoder with the original classifier's residual correction. Native fractional reports stay unchanged. GeoFatigue offsets are inner-cross-fitted by person. External fitting measurements can fit normalization in every sensor variant, including zero auxiliary loss; the pure incumbent control uses no sensor correction."}
    if path.exists():
        report = json.loads(path.read_text(encoding="utf-8"))
        if any(report.get(k) != v for k, v in signature.items()):
            raise ValueError("Frozen joint-source neural experiment changed")
    if not report["results"]:
        path.write_text(json.dumps(report, indent=2, allow_nan=False)+"\n", encoding="utf-8")
    folds = list(GroupKFold(n_splits=5).split(train, groups=train["group_key"]))
    caches = []
    for number, (fit, val) in enumerate(folds):
        if set(train.iloc[fit]["group_key"]) & set(train.iloc[val]["group_key"]):
            raise ValueError("Joint-source population fit contains validation people")
        cached = prepare_base(train.iloc[fit], signature["core_candidate"])
        caches.append(cached)
        print(f"Joint-source nested baseline {number+1}/5 prepared", flush=True)
    report["folds"] = [{"fit_row_keys": train.iloc[fit]["row_key"].tolist(), "validation_row_keys": train.iloc[val]["row_key"].tolist(),
                        "inner_folds": cache["inner_folds"]} for (fit, val), cache in zip(folds, caches)]
    for candidate in candidates:
        if any(r["candidate"] == candidate for r in report["results"]):
            continue
        predicted = np.empty(len(train), dtype=object)
        losses = []
        for (fit, val), cache in zip(folds, caches):
            model = JointBorg(candidate).fit(train.iloc[fit], external, signature["core_candidate"], cache)
            predicted[val] = model.predict(train.iloc[val])
            losses.append(getattr(model, "training_losses", None))
        scores = [float(accuracy_score(train.iloc[val]["label"], predicted[val])) for _, val in folds]
        report["results"].append({"candidate": candidate, "accuracy_mean": float(np.mean(scores)), "fold_accuracy": scores,
                                  "pooled_oof_accuracy": float(accuracy_score(train["label"], predicted)),
                                  "oof_predictions": predicted.tolist(), "fold_training_losses": losses})
        best = max(report["results"], key=lambda r: r["accuracy_mean"])
        report.update(winner_id=best["candidate"]["id"], best_cv_accuracy=best["accuracy_mean"],
                      status="complete" if len(report["results"]) == len(candidates) else "running")
        content = json.dumps(report, indent=2, allow_nan=False)+"\n"
        path.with_suffix(".tmp").write_text(content, encoding="utf-8")
        path.write_text(content, encoding="utf-8")
        print(f"Four-source neural transfer {len(report['results'])}/{len(candidates)}: exact CV={np.mean(scores):.6f}, best={best['accuracy_mean']:.6f}", flush=True)
    expected = json.loads((RESEARCH / "calibrated-alternatives-v1/selection.json").read_text())
    expected = next(r["oof_predictions"] for r in expected["results"] if r["candidate"]["id"] == "alternative-023")
    np.testing.assert_array_equal(report["results"][0]["oof_predictions"], expected)
    print("Joint-source incumbent control reproduces all 487 original OOF decisions", flush=True)


if __name__ == "__main__":
    select()
