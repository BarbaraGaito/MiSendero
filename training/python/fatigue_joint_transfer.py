"""Shared sensor learning from four audited sources, with separate outcomes.

External native CR10 outcomes supervise separate continuous heads. The shared
sensor encoder also feeds a regularized correction to the original Borg MLP.
Its fitting offsets are generated by inner participant cross-fitting. Source
labels never become GeoFatigue labels or extra validation/test cases.
"""
